"""Camoufox launch defaults: the options every browser-lane session uses.

Values ported from the working browser backend in `D:/project`
(`camoufox_boost.camoufox_options`). They are not free: each one either cuts
memory/CPU or keeps the anti-detect fingerprint intact, and the comments say
which. The fingerprint itself is generated by Camoufox; nothing here weakens it.

Nothing imports camoufox at module level. The package is optional at import
time (a worker must boot without it), so it is resolved lazily inside the
options builder.
"""

from __future__ import annotations

import importlib
from typing import Any

# Firefox preferences: fewer helper processes, no telemetry, no caches.
# WebGL stays on — it is part of the fingerprint and hCaptcha probes it.
FIREFOX_PREFS: dict[str, bool | int | str] = {
    # A single content process is enough for one page per browser.
    "dom.ipc.processCount": 1,
    "dom.ipc.processCount.webIsolated": 1,
    "fission.autostart": False,
    "browser.tabs.remote.autostart": True,
    # No telemetry, crash reporting or background update traffic.
    "toolkit.telemetry.enabled": False,
    "toolkit.telemetry.unified": False,
    "datareporting.healthreport.uploadEnabled": False,
    "datareporting.policy.dataSubmissionEnabled": False,
    "app.update.enabled": False,
    "extensions.update.enabled": False,
    "browser.startup.homepage_override.mstone": "ignore",
    "browser.shell.checkDefaultBrowser": False,
    # Keep session history and caches small: one page, then discard.
    "browser.cache.disk.enable": False,
    "browser.cache.memory.capacity": 16384,
    "browser.cache.memory.max_entry_size": 512,
    "browser.sessionstore.interval": 9999999,
    "browser.sessionstore.max_tabs_undo": 0,
    "browser.sessionhistory.max_entries": 2,
    "browser.sessionhistory.max_total_viewers": 0,
    "image.mem.surface_cache.max_size_kb": 8192,
    "image.mem.shared": True,
    # No media pipeline, autoplay, WebRTC or prefetching.
    "media.autoplay.default": 5,
    "media.peerconnection.enabled": False,
    "media.memory_cache_max_size": 8192,
    "media.cache_size": 0,
    "media.rdd-process.enabled": False,
    "network.prefetch-next": False,
    "network.dns.disablePrefetch": True,
    "network.process.enabled": False,
    # Less background work: no safebrowsing, spellcheck, reader mode, prelaunch.
    "browser.safebrowsing.malware.enabled": False,
    "browser.safebrowsing.phishing.enabled": False,
    "layout.spellcheckDefault": 0,
    "reader.parse-on-load.enabled": False,
    "general.smoothScroll": False,
    "browser.tabs.unloadOnLowMemory": True,
    "dom.ipc.processPrelaunch.enabled": False,
    "gfx.font_rendering.fallback.async": False,
}


def default_addons() -> list[Any] | None:
    """Camoufox bundled addons to skip at launch — uBlock Origin.

    UBO roughly doubles resident memory on this build (~1.1 GB vs ~0.55 GB for
    a blank page), and the captcha flow does not need its filtering. Returns
    `None` when camoufox is not installed, so options can still be built (and
    asserted) in tests.
    """
    try:
        module = importlib.import_module("camoufox")
    except ImportError:
        return None
    addons = getattr(module, "DefaultAddons", None)
    ubo = getattr(addons, "UBO", None)
    return [ubo] if ubo is not None else None


def build_options(
    *,
    headless: bool | str,
    proxy: dict[str, str] | None,
    geoip: bool | str,
    user_data_dir: str,
    humanize: bool = True,
    exclude_addons: list[Any] | None = None,
) -> dict[str, Any]:
    """Camoufox launcher kwargs for one fresh per-task profile.

    `geoip` is the exit IP when the task carries a proxy, `True` (host-based)
    when it does not — the provider refuses the host fallback for proxied tasks,
    so `True` never leaks a datacenter location behind someone's proxy.
    """
    options: dict[str, Any] = {
        "headless": headless,
        "persistent_context": True,
        "os": "windows",
        "geoip": geoip,
        "block_webrtc": True,
        "humanize": humanize,
        "enable_cache": False,
        "user_data_dir": user_data_dir,
        "firefox_user_prefs": dict(FIREFOX_PREFS),
        "proxy": proxy or None,
    }
    addons = exclude_addons if exclude_addons is not None else default_addons()
    if addons:
        options["exclude_addons"] = list(addons)
    return options


__all__ = ["FIREFOX_PREFS", "build_options", "default_addons"]
