"""MTCaptcha "fold" proof-of-work and key-history string.

The challenge carries an optional `foldChlg` object (`fseed`, `fslots`,
`fdepth`). The iframe derives `fa` from it (the proof submitted with the
answer) and `kt` (a key-history obfuscation of the same seed). Both are pure
functions of the seed/depth/slots, so they port directly; the reference is
`kalkih/mtcaptcha-client/crypto.js` (MIT) which lifts them out of
`iframe.html`. Vectors generated by running that JS are pinned in
`tests/solvers/interactive/test_mtcaptcha.py`.

When `hasFoldChlg` is false the wire expects the literal `"$"` for both.
"""

from __future__ import annotations

_ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"
_CHAR_TO_INT = {char: index for index, char in enumerate(_ALPHABET)}
_INT32 = 0x100000000


def _int32(value: int) -> int:
    value &= _INT32 - 1
    return value - _INT32 if value >= 0x80000000 else value


def _str_to_ints(seed: str) -> list[int]:
    try:
        return [_CHAR_TO_INT[char] for char in seed]
    except KeyError as exc:
        raise ValueError(f"fold seed is not URL-safe base64: {exc}") from exc


def _fold(values: list[int], count: int) -> list[int]:
    mirrored = list(reversed(values))
    current = list(values)
    y = z = 0
    for offset in range(1, count + 1):
        for index in range(len(values)):
            pair = (current[index] + mirrored[(index + offset) % len(mirrored)]) * 73
            current[index] = (pair // 8 + y + z) % 64
            z = y // 2
            y = current[index] // 2
    return current


def _hash_ints(values: list[int]) -> int:
    hsh = 0
    for value in values:
        hsh = _int32(hsh * 31 + value)
    return abs(hsh)


def solve_fold(seed: str, slots: int, depth: int) -> str:
    """`fa`: `fslots` folded hashes, two base64 chars each."""
    if not seed or slots < 1:
        return "0"
    ints = _str_to_ints(seed)
    out: list[str] = []
    for _ in range(slots):
        ints = _fold(ints, 31)
        hashed = _hash_ints(_fold(ints, depth))
        out.append(_ALPHABET[(hashed % 4096) >> 6] + _ALPHABET[hashed % 64])
    return "".join(out)


def kees_string(seed: str) -> str:
    """`kt`: key history — each base64 int XORed with its predecessor."""
    if not seed:
        return "$"
    ints = _str_to_ints(seed)
    history = [0] * len(ints)
    previous = ints[-1]
    for index, value in enumerate(ints):
        history[index] = value ^ previous
        previous = value
    return "".join(_ALPHABET[value] for value in history)


def fold_params(fold: dict | None) -> tuple[str, str, str]:
    """(fa, kt, fs) for the query string; `("$", "$", "")` without a fold."""
    if not isinstance(fold, dict):
        return "$", "$", ""
    seed = str(fold.get("fseed") or "")
    try:
        slots = int(fold.get("fslots") or 0)
        depth = int(fold.get("fdepth") or 0)
    except (TypeError, ValueError):
        return "$", "$", ""
    if not seed or slots < 1:
        return "$", "$", ""
    return solve_fold(seed, slots, depth), kees_string(seed), seed
