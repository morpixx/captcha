"""MTCaptcha client pulse: the `mtv1Pulse` cookie value.

MTCaptcha's iframe computes a 26-character "base4096" fingerprint before it
asks for the challenge image. It is a documented-nowhere XOR-fold of 13 small
integers (UA/host/language/hardware hashes, time slices, a random pair), and
the server sets/reads it as a risk cookie. The reference is the JavaScript in
`mtcv1/client/iframe.html` (2026-10-23 build) and the MIT-licensed port in
`kalkih/mtcaptcha-client/crypto.js`; the vectors in
`tests/solvers/interactive/test_mtcaptcha.py` are generated by running that
JS with Math.random/Date.now stubbed.

It is a cookie, not a proof: a missing or stale pulse does not mint a token,
it only raises the risk score.
"""

from __future__ import annotations

import math
import os
import random
import re
import time
from datetime import datetime

_ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"
_HOST_RE = re.compile(r"^(?:https?://)?(?:[^@/\n]+@)?(?:www.)?([^:/\n]+)", re.IGNORECASE)
_INT32 = 0x100000000


def _int32(value: int) -> int:
    """JavaScript `value & value` semantics: keep the low 32 bits, signed."""
    value &= _INT32 - 1
    return value - _INT32 if value >= 0x80000000 else value


def _hash_str(text: str) -> int:
    """Port of the iframe's `hashStr`: `hsh = (hsh << 5) - hsh + code`."""
    hsh = 0
    for char in text:
        hsh = _int32(hsh * 31 + ord(char))
    return hsh


def _b64_char(value: int) -> str:
    return _ALPHABET[value % 64]


def _b4096(value: int) -> str:
    return _b64_char(value >> 6) + _b64_char(value)


def _host_match(site_url: str) -> str:
    match = _HOST_RE.match(site_url)
    return match.group(1) if match else ""


def local_offset_minutes(now: datetime | None = None) -> int:
    """`Date.getTimezoneOffset()`: minutes west of UTC (positive for the US)."""
    offset = (now or datetime.now().astimezone()).utcoffset()
    return 0 if offset is None else -int(offset.total_seconds() // 60)


def pulse(
    site_url: str,
    *,
    user_agent: str,
    language: str = "en-US",
    hardware_concurrency: int | None = None,
    now_ms: int | None = None,
    rand: tuple[float, float] | None = None,
    tz_offset_minutes: int | None = None,
) -> str:
    """Build the `mtv1Pulse` cookie value.

    `rand`/`now_ms`/`tz_offset_minutes` are injection seams for the reference
    vectors; the production path takes two fresh uniforms and the wall clock.
    """
    first, second = rand if rand is not None else (random.random(), random.random())
    stamp = int((now_ms if now_ms is not None else time.time() * 1000) // 1000)
    offset = local_offset_minutes() if tz_offset_minutes is None else tz_offset_minutes
    hw = hardware_concurrency if hardware_concurrency is not None else (os.cpu_count() or 1)

    values = [0, 1, math.floor(first * 4095.99), math.floor(second * 4095.99)]
    values.append(math.floor(stamp / 0x400000) % 0x1000)
    values.append(((stamp % 0x400000) >> 11) % 0x1000)
    values.append((stamp % 0x400000) % 0x800)
    values.append(abs(math.floor(offset / 10) % 0x1000))
    values.append(abs(_hash_str(user_agent.lower())) % 0x1000)
    values.append(abs(_hash_str(_host_match(site_url).lower())) % 0x1000)
    values.append(abs(_hash_str(language.lower())) % 0x1000)
    values.append(hw % 0x1000)

    folded = 0
    for value in values:
        folded = _int32(folded * 31 + value)
    values.append(abs(folded) % 0x1000)

    for index in range(4, len(values)):
        values[index] ^= values[2 + (index % 2)]

    return "".join(_b4096(value) for value in values)
