"""Temu / PDD aegis slider with the anti_content fingerprint.

Flow:
  1. POST captcha/init with the client-captured anti-content header ->
     captchaId, background/piece images, challenge variant.
  2. Solve the variant through the CV registry (slider or semantic click).
  3. POST captcha/verify with the geometry + pointer trace and the same
     anti-content header.
  4. Return the session cookies (and a pass token when one comes back); the
     catalog projects Temu as a cookie engine.

anti_content is generated by the page's SDK and cannot be re-derived from a
sitekey, so a task that omits it is unsolvable here: payload mode means the
client captured it from the session it wants solved. We say so instead of
sending an empty header and reporting whatever 403 comes back as success.
"""

from __future__ import annotations

import base64
import time
from typing import Any
from urllib.parse import urlparse

from captcha.domain import CaptchaType, SolverResult, Task
from captcha.domain.enums import SolveMode
from captcha.domain.errors import ChallengeExpiredError, ConfigError, UnsolvableError
from captcha.solvers.base import SolverContext, SolverInfo
from captcha.solvers.registry import register_solver

from .._base import InteractiveBase
from . import endpoints as ep
from . import wire


@register_solver
class TemuSolver(InteractiveBase):
    """Temu aegis challenge. Payload must carry anti_content and a page URL."""

    info = SolverInfo(
        name="temu",
        types=(CaptchaType.TEMU,),
        http=True,
        needs_js_runtime=True,  # anti_content is JS-signed
        experimental=True,
    )

    async def solve_http(self, task: Task, ctx: SolverContext) -> SolverResult:
        payload = task.payload
        anti = wire.anti_content(payload)
        if not anti:
            raise UnsolvableError(
                "temu needs the client-captured anti_content header",
                context={
                    "need": "anti_content",
                    "hint": "capture the anti-content request header from the page session",
                    "keys": sorted(payload),
                },
            )
        if ctx.http is None:
            raise ConfigError("temu solver needs ctx.http", context={"solver": self.info.name})

        start = time.monotonic()
        headers = _headers(task, anti)
        init_body = {
            "scene": str(_first(payload, "scene", "captcha_scene") or ""),
            "captchaId": str(_first(payload, "captcha_id", "captchaId") or ""),
            "bizType": str(_first(payload, "biz_type", "bizType") or ""),
        }
        resp = await ctx.http.post(ep.CAPTCHA_INIT, json=init_body, headers=headers)
        root = wire.json_object(resp, "temu init")
        wire.raise_for_failure(root, "temu init")
        challenge = wire.parse_challenge(root)

        kind = wire.variant_kind(challenge["variant"], bool(challenge["piece"]), challenge["prompt"])
        if kind == "grid":
            raise UnsolvableError(
                "temu grid variant is not wired: the CV registry has no tile classifier for this layout",
                context={"variant": challenge["variant"], "keys": sorted(root)},
            )

        bg = await _image(ctx, _absolute(challenge["bg"]), headers)
        cv_payload: dict[str, Any] = {"bg": wire.b64(bg), "seed": payload.get("seed")}
        if kind == "slider":
            if not challenge["piece"]:
                raise UnsolvableError(
                    "temu slider challenge has no piece image",
                    context={"variant": challenge["variant"], "keys": sorted(root)},
                )
            cv_payload["piece"] = wire.b64(await _image(ctx, _absolute(challenge["piece"]), headers))
            cv_kind = CaptchaType.SLIDER
        else:
            if not challenge["prompt"]:
                raise UnsolvableError(
                    "temu click challenge has no target text",
                    context={"variant": challenge["variant"], "keys": sorted(root)},
                )
            cv_payload["image"] = cv_payload.pop("bg")
            cv_payload["target"] = challenge["prompt"]
            cv_kind = CaptchaType.CLICK

        cv = await self._solve_cv(cv_kind, task, ctx, cv_payload)
        body = wire.answer_body(challenge, cv, kind, payload.get("seed"))
        vr = await ctx.http.post(ep.CAPTCHA_VERIFY, json=body, headers=headers)
        vroot = wire.json_object(vr, "temu verify")
        wire.raise_for_failure(vroot, "temu verify")

        cookies = wire.extract_cookies(vr, vroot)
        token = wire.find_token(vroot)
        if not cookies and not token:
            raise ChallengeExpiredError(
                "temu verify returned no session cookie or token (challenge consumed or rejected)",
                context={"keys": sorted(vroot), "captchaId": challenge["captcha_id"]},
            )

        extra: dict[str, Any] = {
            "cookies": cookies,
            "domain": _host(task),
            "challengeType": challenge["variant"] or kind,
            "captchaId": challenge["captcha_id"],
        }
        ua = _first(payload, "user_agent", "userAgent") or task.user_agent
        if ua:
            extra["userAgent"] = str(ua)
        return SolverResult(
            token=token or None,
            extra=extra,
            solve_mode=SolveMode.HTTP,
            latency_ms=(time.monotonic() - start) * 1000.0,
        )


async def _image(ctx: SolverContext, url: str, headers: dict[str, str]) -> bytes:
    if url.startswith("data:"):
        try:
            return base64.b64decode(url.split(",", 1)[1])
        except Exception as exc:
            raise UnsolvableError("temu image is a broken data URI", context={"head": url[:48]}) from exc
    resp = await ctx.http.get(url, headers=headers)
    wire.raise_for_status(resp, "temu image")
    if not resp.body:
        raise UnsolvableError("temu image body is empty", context={"url": url})
    return resp.body


def _headers(task: Task, anti: str) -> dict[str, str]:
    payload = task.payload
    headers = {
        "accept": "application/json, text/plain, */*",
        "content-type": "application/json",
        "anti-content": anti,
        "x-requested-with": "XMLHttpRequest",
    }
    ua = _first(payload, "user_agent", "userAgent") or task.user_agent
    if ua:
        headers["user-agent"] = str(ua)
    page = _page(task)
    if page:
        headers["referer"] = page
        if "://" in page:
            headers["origin"] = page.split("/", 3)[0] + "//" + page.split("/", 3)[2]
    lang = _first(payload, "lang", "language") or task.language
    if lang:
        headers["accept-language"] = str(lang)
    return headers


def _page(task: Task) -> str:
    payload = task.payload
    return str(_first(payload, "pageurl", "websiteURL", "site_url") or task.site_url or "")


def _host(task: Task) -> str:
    page = _page(task)
    if not page:
        return ep.PAGE_HOST
    return urlparse(page if "//" in page else "https://" + page).hostname or ep.PAGE_HOST


def _absolute(url: str) -> str:
    if url.startswith(("http://", "https://", "data:")):
        return url
    return ep.PAGE_BASE + ("/" if not url.startswith("/") else "") + url


def _first(data: dict[str, Any], *keys: str) -> Any:
    for key in keys:
        value = data.get(key)
        if value not in (None, "", [], {}):
            return value
    return None
