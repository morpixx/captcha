async def test_image_is_base64_decoded(monkeypatch: pytest.MonkeyPatch) -> None:
    raw = b"\x89PNG\r\n"
    calls = _stub_ocr(monkeypatch)
    http = HTTP({ep.GET_CHALLENGE: _challenge(), ep.GET_IMAGE: _image(raw), ep.SOLVE_CHALLENGE: _solved()})

    await MTCaptchaSolver().solve_http(_task(), SolverContext(http=http))

    assert calls[0][1]["image"] == raw
