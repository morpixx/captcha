# ---- the flow ---------------------------------------------------------------


async def test_full_flow_sends_fold_and_returns_server_token(monkeypatch: pytest.MonkeyPatch) -> None:
    calls = _stub_ocr(monkeypatch)
    http = _http()
    task = _task(user_agent=UA)

    result = await MTCaptchaSolver().solve_http(task, SolverContext(http=http))

    assert result.token == TOKEN
    assert result.solve_mode.value == "http"
    assert build_solution(CaptchaType.MTCAPTCHA, msgspec.structs.asdict(result)) == {
        "token": TOKEN,
        "userAgent": UA,
    }

    challenge_call = http.call("GET", ep.GET_CHALLENGE)
    assert challenge_call["params"]["sk"] == SITEKEY
    assert challenge_call["params"]["bd"] == "shop.test"
    assert challenge_call["params"]["tsh"] == transaction_signature(SITEKEY)
    assert challenge_call["params"]["tp"] == "s"
    assert "sitekey=" + SITEKEY in challenge_call["headers"]["Referer"]

    image_call = http.call("GET", ep.GET_IMAGE)
    assert image_call["params"]["ct"] == "CT-1"
    assert image_call["params"]["fa"] == "FCGh"
    assert image_call["params"]["ss"] == challenge_call["params"]["ss"]
    assert "mtv1Pulse=" in image_call["headers"]["Cookie"]

    solve_call = http.call("GET", ep.SOLVE_CHALLENGE)
    assert solve_call["params"]["st"] == "AB12"
    assert solve_call["params"]["fa"] == "FCGh"
    assert solve_call["params"]["kt"] == "tlfhfdf131z1471"
    assert solve_call["params"]["fs"] == "AbCdEf0123-_xyz"
    assert solve_call["params"]["ct"] == "CT-1"
    assert solve_call["params"]["ss"] == challenge_call["params"]["ss"]

    assert calls and calls[0][0] is CaptchaType.IMAGE_TO_TEXT
    assert calls[0][1]["image"] == b"png"
    assert calls[0][1]["lang"] == "en"


async def test_no_fold_challenge_uses_dollar(monkeypatch: pytest.MonkeyPatch) -> None:
    _stub_ocr(monkeypatch)
    http = _http(hasFoldChlg=False)
    result = await MTCaptchaSolver().solve_http(_task(), SolverContext(http=http))

    assert result.token == TOKEN
    assert http.call("GET", ep.GET_IMAGE)["params"]["fa"] == "$"
    assert http.call("GET", ep.SOLVE_CHALLENGE)["params"]["kt"] == "$"


async def test_empty_ocr_retries_the_challenge(monkeypatch: pytest.MonkeyPatch) -> None:
    _stub_ocr(monkeypatch, text="   ")
    http = _http()
    with pytest.raises(CaptchaError, match="no text"):
        await MTCaptchaSolver().solve_http(_task(), SolverContext(http=http))
    assert ("GET", ep.SOLVE_CHALLENGE) not in [call[:2] for call in http.calls]


async def test_rejected_answer_is_a_spent_challenge(monkeypatch: pytest.MonkeyPatch) -> None:
    _stub_ocr(monkeypatch)
    http = HTTP(
        {
            ep.GET_CHALLENGE: _challenge(),
            ep.GET_IMAGE: _image(),
            ep.SOLVE_CHALLENGE: _solved(verified=False),
        }
    )
    with pytest.raises(ChallengeExpiredError, match="rejected"):
        await MTCaptchaSolver().solve_http(_task(), SolverContext(http=http))


async def test_verified_without_vt_is_protocol_drift(monkeypatch: pytest.MonkeyPatch) -> None:
    _stub_ocr(monkeypatch)
    http = HTTP(
        {
            ep.GET_CHALLENGE: _challenge(),
            ep.GET_IMAGE: _image(),
            ep.SOLVE_CHALLENGE: {"result": {"verifyResult": {"isVerified": True, "verifiedToken": {}}}},
        }
    )
    with pytest.raises(CaptchaError, match="v1"):
        await MTCaptchaSolver().solve_http(_task(), SolverContext(http=http))


