"""MTCaptcha HTTP flow: the wire params, the fold proof, and the token hand-off.

No network. The three vendor calls are replayed from canned JSON, the OCR
delegate is stubbed, and the reference vectors for the two ported pure-JS
functions are pinned against outputs generated by running `mtcaptcha-client`
under Node (see `pulse.py`/`fold.py`). The point is that the solver stops at
`verifyResult.verifiedToken.vt` and never builds a `v1(...)` token itself.
"""

from __future__ import annotations

import base64
import hashlib
from typing import Any

import msgspec
import pytest
from tests.solvers.interactive._fakes import HTTP, Garbage, Reply, make_task

from captcha.domain import CaptchaType, SolverResult, Task
from captcha.domain.errors import CaptchaError, ChallengeExpiredError, ConfigError, UnsolvableError
from captcha.domain.solution import build_solution
from captcha.solvers import SolverContext
from captcha.solvers.interactive.mtcaptcha import endpoints as ep
from captcha.solvers.interactive.mtcaptcha import pulse as pulse_mod
from captcha.solvers.interactive.mtcaptcha.fold import kees_string, solve_fold
from captcha.solvers.interactive.mtcaptcha.solver import MTCaptchaSolver
from captcha.solvers.interactive.mtcaptcha.wire import transaction_signature

SITE_URL = "https://shop.test/login"
SITEKEY = "MTPublic-tqNCRE0GS"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:147.0) Gecko/20100101 Firefox/147.0"
TOKEN = "v1(00cc43a5,1adfe4b4,MTPublic-tqNCRE0GS,0080ab49abc)"
FOLD = {"fseed": "AbCdEf0123-_xyz", "fslots": 2, "fdepth": 3}


def _task(payload: dict[str, Any] | None = None, **kwargs: Any) -> Task:
    return make_task(CaptchaType.MTCAPTCHA, payload, site_url=SITE_URL, sitekey=SITEKEY, **kwargs)


def _challenge(**challenge: Any) -> dict[str, Any]:
    body = {"ct": "CT-1", "tid": "TID-1", "hasFoldChlg": True, "foldChlg": FOLD}
    body.update(challenge)
    return {"result": {"challenge": body}}


def _image(raw: bytes = b"png") -> dict[str, Any]:
    return {"result": {"img": {"image64": base64.b64encode(raw).decode()}}}


def _solved(token: str = TOKEN, *, verified: bool = True) -> dict[str, Any]:
    verify: dict[str, Any] = {"isVerified": verified, "code": 2000, "msg": "ok"}
    if verified:
        verify["verifiedToken"] = {"vt": token}
    return {"result": {"verifyResult": verify}}


def _http(token: str = TOKEN, **challenge: Any) -> HTTP:
    return HTTP(
        {
            ep.GET_CHALLENGE: _challenge(**challenge),
            ep.GET_IMAGE: _image(),
            ep.SOLVE_CHALLENGE: _solved(token),
        }
    )


def _stub_ocr(monkeypatch: pytest.MonkeyPatch, text: str = "AB12") -> list[tuple[CaptchaType, dict[str, Any]]]:
    calls: list[tuple[CaptchaType, dict[str, Any]]] = []

    async def fake(self: Any, kind: CaptchaType, task: Task, ctx: SolverContext, payload: dict[str, Any]):
        calls.append((kind, payload))
        return SolverResult(text=text)

    monkeypatch.setattr(MTCaptchaSolver, "_solve_cv", fake)
    return calls


